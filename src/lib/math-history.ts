/** 오늘(한국 시간) 날짜의 일련번호 — 날마다 1씩 커진다 */
export function kstDayNumber(now = new Date()) {
  return Math.floor((now.getTime() + 9 * 60 * 60 * 1000) / 86_400_000)
}

/** 오늘의 이야기 (날마다 바뀌고, 모두 한 번씩 돌면 처음부터) */
export function storyOfDay(now = new Date()) {
  return STORIES[kstDayNumber(now) % STORIES.length]
}

/** 오늘 것이 아닌 이야기 하나를 무작위로 */
export function randomStory(exceptId?: number) {
  const pool = STORIES.filter((s) => s.id !== exceptId)
  return pool[Math.floor(Math.random() * pool.length)]
}
